age = input("Введите возраст заёмщика: ")
age = int(age)
ezhmdoh = input("Введите ежемесячный доход заёмщика: ")
ezhmdoh = float(ezhmdoh)
razmkred = input("Введите размер запрашиваемого кредита: ")
razmkred = float(razmkred)
srokkred = input("Введите на какой срок берётся кредит (в месяцах): ")
srokkred = int(srokkred)
kredist = input("Введите какого типа кредитная история заёмщика (отличная/хорошая/удовлетворительная/плохая): ")
poruch = input("Наличие поручителей (да/нет): ")
zalog = input("Наличие залога (да/нет): ")

#примерный ежемесячный платеж
platezh = razmkred / srokkred

# какой процент от дохода уходит на кредит DTI (Debt-to-Income) — ключевой показатель в банках
dti = (platezh / ezhmdoh) * 100

score = 0  # Изначально баллов 0

# Оценка возраста
if 25 <= age <= 55:
    score += 10  # Самый надежный возраст
elif 18 <= age <= 24 or 56 <= age <= 63:
    score += 5   # Молодые или предпенсионные
else:
    score -= 10  # Пенсионеры или слишком молодые

# Оценка кредитной истории
if kredist == 'отличная':
    score += 20
elif kredist == 'хорошая':
    score += 10
elif kredist == 'удовлетворительная':
    score += 0
elif kredist == 'плохая':
    score -= 30

# Оценка поручителей
if poruch == 'да':
    score += 10

# Оценка залога
if zalog == 'да':
    score += 15

# Оценка долговой нагрузки (DTI)
if dti <= 25:
    score += 10  # Меньше 25% дохода - отлично
elif 25 < dti <= 50:
    score += 0   # Нормально
elif 50 < dti <= 60:
    score -= 10  # Много
else:
    score -= 25  # Слишком много (больше 60%)

print("\nРЕЗУЛЬТАТЫ АНАЛИЗА:")
print(f"Примерный ежемесячный платеж: {platezh:.2f} руб.")
print(f"Соотношение кредита к доходу: {dti:.1f}%")
print(f"Итоговый балл надежности: {score}")

# Проверяем на наличие "стоп-факторов"
if kredist == 'плохая' or dti > 60 or age < 18 or age > 70:
    print("\nКатегория риска: КРИТИЧЕСКИЙ")
    print("Предлагаемая процентная ставка: Отказ в выдаче")
    print("Рекомендация: ОТКЛОНИТЬ. Причина: плохая кредитная история, слишком большая долговая нагрузка или возрастные ограничения.")

else:
    if score >= 40:
        print("\nКатегория риска: НИЗКИЙ")
        print("Предлагаемая процентная ставка: 15%")
        print("Рекомендация: ОДОБРИТЬ.")
    elif 20 <= score < 40:
        print("\nКатегория риска: СРЕДНИЙ")
        print("Предлагаемая процентная ставка: 19%")
        print("Рекомендация: ОДОБРИТЬ.")
    else:
        print("\nКатегория риска: ВЫСОКИЙ")
        print("Предлагаемая процентная ставка: 26%")
        print("Рекомендация: ОДОБРИТЬ ПОД ПОВЫШЕННЫЙ ПРОЦЕНТ (или потребовать залог/поручителя).")